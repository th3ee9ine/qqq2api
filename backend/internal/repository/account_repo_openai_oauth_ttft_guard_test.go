func TestOpenAIOAuthTTFTGuardProbeLifecyclePostgres(t *testing.T) {
	ctx, tx, repo := openAIOAuthTTFTPostgresFixture(t)
	now := time.Now().UTC().Truncate(time.Second)
	id := ttftGuardInsertAccount(t, ctx, tx, map[string]any{"unrelated": "keep"})
	changed, err := repo.PauseOpenAIOAuthTTFT(ctx, id, "gpt-5", now.Add(-30*time.Minute), now)
	require.NoError(t, err)
	require.True(t, changed)
	claimed, err := repo.ClaimOpenAIOAuthTTFTProbe(ctx, now, "first-lease", now.Add(2*time.Minute))
	require.NoError(t, err)
	require.NotNil(t, claimed)
	require.Equal(t, id, claimed.ID)
	state, valid := service.ParseOpenAIOAuthTTFTGuardState(claimed.Extra)
	require.True(t, valid)
	require.Equal(t, "first-lease", state.ProbeToken)
	duplicate, err := repo.ClaimOpenAIOAuthTTFTProbe(ctx, now.Add(time.Minute), "competing-lease", now.Add(3*time.Minute))
	require.NoError(t, err)
	require.Nil(t, duplicate, "an unexpired lease excludes duplicate probes")
	claimed, err = repo.ClaimOpenAIOAuthTTFTProbe(ctx, now.Add(2*time.Minute), "replacement-lease", now.Add(4*time.Minute))
	require.NoError(t, err)
	require.NotNil(t, claimed, "an abandoned lease becomes claimable at its deadline")
	changed, err = repo.FinishOpenAIOAuthTTFTProbe(ctx, id, "first-lease", true, now)
	require.NoError(t, err)
	require.False(t, changed, "the expired worker cannot complete a replacement lease")
	next := now.Add(30 * time.Minute)
	changed, err = repo.FinishOpenAIOAuthTTFTProbe(ctx, id, "replacement-lease", false, next)
	require.NoError(t, err)
	require.True(t, changed)
	account, err := repo.GetByID(ctx, id)
	require.NoError(t, err)
	state, valid = service.ParseOpenAIOAuthTTFTGuardState(account.Extra)
	require.True(t, valid)
	require.Equal(t, next, state.NextProbeAt)
	require.Empty(t, state.ProbeToken)
	require.Nil(t, state.ProbeLeaseUntil)
	claimed, err = repo.ClaimOpenAIOAuthTTFTProbe(ctx, next.Add(-time.Second), "too-early", next.Add(time.Minute))
	require.NoError(t, err)
	require.Nil(t, claimed)
	claimed, err = repo.ClaimOpenAIOAuthTTFTProbe(ctx, next, "recovery", next.Add(2*time.Minute))
	require.NoError(t, err)
	require.NotNil(t, claimed)
	// An admin and independent failure handlers can change these while the probe runs.
	unrelatedUntil := now.Add(3 * time.Hour)
	_, err = tx.ExecContext(ctx, `UPDATE accounts SET schedulable = false,
		temp_unschedulable_until = $2, temp_unschedulable_reason = 'manual pause',
		rate_limit_reset_at = $2, overload_until = $2 WHERE id = $1`, id, unrelatedUntil)
	require.NoError(t, err)
	changed, err = repo.FinishOpenAIOAuthTTFTProbe(ctx, id, "recovery", true, next)
	require.NoError(t, err)
	require.True(t, changed)
	account, err = repo.GetByID(ctx, id)
	require.NoError(t, err)
	require.NotContains(t, account.Extra, service.OpenAIOAuthTTFTGuardStateExtraKey)
	require.Equal(t, "keep", account.Extra["unrelated"])
	require.False(t, account.Schedulable)
	require.Equal(t, "manual pause", account.TempUnschedulableReason)
	require.Equal(t, unrelatedUntil, *account.TempUnschedulableUntil)
	require.Equal(t, unrelatedUntil, *account.RateLimitResetAt)
	require.Equal(t, unrelatedUntil, *account.OverloadUntil)
	changed, err = repo.FinishOpenAIOAuthTTFTProbe(ctx, id, "recovery", true, next)
	require.NoError(t, err)
	require.False(t, changed)
}

func TestOpenAIOAuthTTFTGuardClaimSkipsMalformedAndFutureStatesPostgres(t *testing.T) {
	ctx, tx, repo := openAIOAuthTTFTPostgresFixture(t)
	now := time.Now().UTC().Truncate(time.Second)
	for _, invalid := range []map[string]any{
		{},
		{"paused_at": "2026-02-31T00:00:00Z", "next_probe_at": now.Format(time.RFC3339), "model": "gpt-5"},
		{"paused_at": now.Format(time.RFC3339), "next_probe_at": "2026-02-31T00:00:00Z", "model": "gpt-5"},
		{"paused_at": now.Format(time.RFC3339), "next_probe_at": now.Format(time.RFC3339), "model": "gpt-5", "probe_lease_until": "broken"},
		{"paused_at": now.Format(time.RFC3339), "next_probe_at": now.Add(time.Minute).Format(time.RFC3339), "model": "gpt-5"},
	} {
		ttftGuardInsertAccount(t, ctx, tx, map[string]any{service.OpenAIOAuthTTFTGuardStateExtraKey: invalid})
	}
	due := ttftGuardTestState(now)
	due["next_probe_at"] = now.Add(-time.Second + 123456789*time.Nanosecond).Format(time.RFC3339Nano)
	id := ttftGuardInsertAccount(t, ctx, tx, map[string]any{service.OpenAIOAuthTTFTGuardStateExtraKey: due})
	claimed, err := repo.ClaimOpenAIOAuthTTFTProbe(ctx, now, "due-account", now.Add(time.Minute))
	require.NoError(t, err, "malformed metadata must not abort a claim query")
	require.NotNil(t, claimed)
	require.Equal(t, id, claimed.ID)
}

func TestOpenAIOAuthTTFTGuardOwnerScopePostgres(t *testing.T) {
	ctx, tx, repo := openAIOAuthTTFTPostgresFixture(t)
	now := time.Now().UTC().Truncate(time.Second)
	id := ttftGuardInsertAccount(t, ctx, tx, map[string]any{})
	_, err := tx.ExecContext(ctx, `UPDATE accounts SET account_admin_id = 42 WHERE id = $1`, id)
	require.NoError(t, err)
	otherOwner := context.WithValue(ctx, ctxkey.AccountAdminID, int64(7))
	owner := context.WithValue(ctx, ctxkey.AccountAdminID, int64(42))
	changed, err := repo.PauseOpenAIOAuthTTFT(otherOwner, id, "gpt-5", now, now)
	require.NoError(t, err)
	require.False(t, changed)
	changed, err = repo.PauseOpenAIOAuthTTFT(owner, id, "gpt-5", now, now)
	require.NoError(t, err)
	require.True(t, changed)
	claimed, err := repo.ClaimOpenAIOAuthTTFTProbe(otherOwner, now, "wrong-owner", now.Add(time.Minute))
	require.NoError(t, err)
	require.Nil(t, claimed)
	claimed, err = repo.ClaimOpenAIOAuthTTFTProbe(owner, now, "owner", now.Add(time.Minute))
	require.NoError(t, err)
	require.NotNil(t, claimed)
	changed, err = repo.FinishOpenAIOAuthTTFTProbe(otherOwner, id, "owner", true, now)
	require.NoError(t, err)
	require.False(t, changed)
	changed, err = repo.FinishOpenAIOAuthTTFTProbe(owner, id, "owner", true, now)
	require.NoError(t, err)
	require.True(t, changed)
}
