// These tests execute the production SQL against an isolated PostgreSQL fixture.
// Only transaction-local temporary tables are created; all changes roll back.
func openAIOAuthTTFTPostgresFixture(t *testing.T) (context.Context, *dbent.Tx, *accountRepository) {
	t.Helper()
	dsn := os.Getenv("QQQ2API_TEST_POSTGRES_DSN")
	if dsn == "" {
		t.Skip("set QQQ2API_TEST_POSTGRES_DSN to an isolated PostgreSQL fixture")
	}
	ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
	t.Cleanup(cancel)
	db, err := sql.Open("postgres", dsn)
	require.NoError(t, err)
	client := dbent.NewClient(dbent.Driver(entsql.OpenDB(dialect.Postgres, db)))
	t.Cleanup(func() { _ = client.Close() })
	tx, err := client.Tx(ctx)
	require.NoError(t, err)
	t.Cleanup(func() { _ = tx.Rollback() })
	_, err = tx.ExecContext(ctx, `CREATE TEMP TABLE accounts (
		id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
		created_at timestamptz NOT NULL DEFAULT NOW(), updated_at timestamptz NOT NULL DEFAULT NOW(),
		deleted_at timestamptz, name text NOT NULL DEFAULT 'fixture', notes text,
		platform text NOT NULL DEFAULT 'openai', type text NOT NULL DEFAULT 'oauth',
		credentials jsonb NOT NULL DEFAULT '{}', extra jsonb,
		proxy_fallback_origin_id bigint, concurrency integer NOT NULL DEFAULT 3,
		load_factor integer, priority integer NOT NULL DEFAULT 50,
		rate_multiplier numeric NOT NULL DEFAULT 1, status text NOT NULL DEFAULT 'active',
		error_message text, last_used_at timestamptz, expires_at timestamptz,
		auto_pause_on_expired boolean NOT NULL DEFAULT true, schedulable boolean NOT NULL DEFAULT true,
		rate_limited_at timestamptz, rate_limit_reset_at timestamptz, overload_until timestamptz,
		temp_unschedulable_until timestamptz, temp_unschedulable_reason text,
		session_window_start timestamptz, session_window_end timestamptz, session_window_status text,
		quota_dimension text NOT NULL DEFAULT 'global', proxy_id bigint, parent_account_id bigint,
		account_admin_id bigint
	) ON COMMIT DROP;
	CREATE TEMP TABLE account_groups (
		account_id bigint, group_id bigint, priority integer, created_at timestamptz
	) ON COMMIT DROP;
	CREATE TEMP TABLE scheduler_outbox (
		id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
		event_type text, account_id bigint, group_id bigint, payload jsonb, dedup_key text
	) ON COMMIT DROP;
	CREATE UNIQUE INDEX ON scheduler_outbox (dedup_key) WHERE dedup_key IS NOT NULL`)
	require.NoError(t, err)
	return ctx, tx, newAccountRepositoryWithSQL(tx.Client(), tx, nil)
}

func ttftGuardTestState(now time.Time) map[string]any {
	return map[string]any{
		"paused_at":     now.Add(-time.Hour).UTC().Format(time.RFC3339),
		"next_probe_at": now.UTC().Format(time.RFC3339),
		"model":         "gpt-5",
	}
}

func ttftGuardInsertAccount(t *testing.T, ctx context.Context, tx *dbent.Tx, extra any) int64 {
	t.Helper()
	var encoded any
	if extra != nil {
		data, err := json.Marshal(extra)
		require.NoError(t, err)
		encoded = string(data)
	}
	rows, err := tx.QueryContext(ctx, `INSERT INTO accounts (extra) VALUES ($1::jsonb) RETURNING id`, encoded)
	require.NoError(t, err)
	defer rows.Close()
	require.True(t, rows.Next())
	var id int64
	require.NoError(t, rows.Scan(&id))
	return id
}

func TestOpenAIOAuthTTFTGuardStateSQLPostgres(t *testing.T) {
	ctx, tx, _ := openAIOAuthTTFTPostgresFixture(t)
	now := time.Now().UTC().Truncate(time.Second)
	modified := func(key string, value any) map[string]any {
		state := ttftGuardTestState(now)
		state[key] = value
		return state
	}
	cases := []struct {
		name  string
		state any
		valid bool
	}{
		{name: "missing"},
		{name: "string", state: "broken"},
		{name: "array", state: []any{ttftGuardTestState(now)}},
		{name: "empty object", state: map[string]any{}},
		{name: "valid", state: ttftGuardTestState(now), valid: true},
		{name: "invalid day", state: modified("paused_at", "2026-02-31T00:00:00Z")},
		{name: "invalid month", state: modified("next_probe_at", "2026-13-01T00:00:00Z")},
		{name: "invalid hour", state: modified("next_probe_at", "2026-02-28T24:00:00Z")},
		{name: "leap second", state: modified("next_probe_at", "2026-02-28T23:59:60Z")},
		{name: "fractional timestamp", state: modified("next_probe_at", "2026-02-28T12:34:56.123456789Z"), valid: true},
		{name: "offset timestamp", state: modified("next_probe_at", "2026-02-28T12:34:56+08:00"), valid: true},
		{name: "missing timestamp", state: modified("paused_at", nil)},
		{name: "non-string timestamp", state: modified("paused_at", 42)},
		{name: "missing model", state: modified("model", nil)},
		{name: "blank model", state: modified("model", " \t\n")},
		{name: "numeric model", state: modified("model", 123)},
		{name: "timestamp whitespace", state: modified("paused_at", " \t"+now.Format(time.RFC3339)+"\n"), valid: true},
		{name: "nil lease", state: modified("probe_lease_until", nil), valid: true},
		{name: "valid lease", state: modified("probe_lease_until", now.Add(time.Minute).Format(time.RFC3339)), valid: true},
		{name: "malformed lease", state: modified("probe_lease_until", "broken")},
		{name: "empty lease", state: modified("probe_lease_until", "")},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			extra := map[string]any{}
			if tc.state != nil {
				extra[service.OpenAIOAuthTTFTGuardStateExtraKey] = tc.state
			}
			id := ttftGuardInsertAccount(t, ctx, tx, extra)
			rows, err := tx.QueryContext(ctx, "SELECT "+openAIOAuthTTFTGuardStateValidSQL("extra")+", "+openAIOAuthTTFTGuardSQL("extra", "platform", "type", "parent_account_id")+" FROM accounts WHERE id = $1", id)
			require.NoError(t, err)
			defer rows.Close()
			require.True(t, rows.Next())
			var valid, schedulable bool
			require.NoError(t, rows.Scan(&valid, &schedulable), "both predicates must return non-null booleans")
			require.Equal(t, tc.valid, valid)
			require.Equal(t, !tc.valid, schedulable)
			_, goValid := service.ParseOpenAIOAuthTTFTGuardState(extra)
			require.Equal(t, goValid, valid, "SQL and in-memory scheduling must agree")
		})
	}
	// SQL NULL extra is distinct from an empty JSON object and must also be safe.
	id := ttftGuardInsertAccount(t, ctx, tx, nil)
	rows, err := tx.QueryContext(ctx, "SELECT "+openAIOAuthTTFTGuardSQL("extra", "platform", "type", "parent_account_id")+" FROM accounts WHERE id = $1", id)
	require.NoError(t, err)
	defer rows.Close()
	require.True(t, rows.Next())
	var schedulable bool
	require.NoError(t, rows.Scan(&schedulable))
	require.True(t, schedulable)
}

func TestOpenAIOAuthTTFTGuardPausePostgres(t *testing.T) {
	ctx, tx, repo := openAIOAuthTTFTPostgresFixture(t)
	now := time.Now().UTC().Truncate(time.Second)
	for _, tc := range []struct {
		name  string
		extra any
		want  bool
	}{
		{name: "null extra", want: true},
		{name: "missing state", extra: map[string]any{"unrelated": "keep"}, want: true},
		{name: "malformed state", extra: map[string]any{service.OpenAIOAuthTTFTGuardStateExtraKey: "broken"}, want: true},
		{name: "existing pause", extra: map[string]any{service.OpenAIOAuthTTFTGuardStateExtraKey: ttftGuardTestState(now)}},
	} {
		t.Run(tc.name, func(t *testing.T) {
			id := ttftGuardInsertAccount(t, ctx, tx, tc.extra)
			changed, err := repo.PauseOpenAIOAuthTTFT(ctx, id, "gpt-5", now, now.Add(30*time.Minute))
			require.NoError(t, err)
			require.Equal(t, tc.want, changed)
			account, err := repo.GetByID(ctx, id)
			require.NoError(t, err)
			state, valid := service.ParseOpenAIOAuthTTFTGuardState(account.Extra)
			require.True(t, valid)
			if tc.want {
				require.Equal(t, now.Add(30*time.Minute), state.NextProbeAt)
			}
			if tc.name == "missing state" {
				require.Equal(t, "keep", account.Extra["unrelated"])
			}
			changed, err = repo.PauseOpenAIOAuthTTFT(ctx, id, "other-model", now, now.Add(time.Hour))
			require.NoError(t, err)
			require.False(t, changed, "a subsequent slow request must not replace the existing pause")
		})
	}
}

func TestOpenAIOAuthTTFTGuardSchedulingScopePostgres(t *testing.T) {
	ctx, tx, repo := openAIOAuthTTFTPostgresFixture(t)
	now := time.Now().UTC().Truncate(time.Second)
	wantIDs := make([]int64, 0)
	for _, tc := range []struct {
		name, platform, accountType string
		parent                      *int64
		guard                       bool
		want                        bool
	}{
		{name: "normal OAuth", platform: service.PlatformOpenAI, accountType: service.AccountTypeOAuth, want: true},
		{name: "paused OAuth", platform: service.PlatformOpenAI, accountType: service.AccountTypeOAuth, guard: true},
		{name: "paused setup token", platform: service.PlatformOpenAI, accountType: service.AccountTypeSetupToken, guard: true},
		{name: "API key imported metadata", platform: service.PlatformOpenAI, accountType: service.AccountTypeAPIKey, guard: true, want: true},
		{name: "Anthropic imported metadata", platform: service.PlatformAnthropic, accountType: service.AccountTypeOAuth, guard: true, want: true},
		{name: "shadow imported metadata", platform: service.PlatformOpenAI, accountType: service.AccountTypeOAuth, parent: new(int64), guard: true, want: true},
	} {
		extra := map[string]any{}
		if tc.guard {
			extra[service.OpenAIOAuthTTFTGuardStateExtraKey] = ttftGuardTestState(now)
		}
		id := ttftGuardInsertAccount(t, ctx, tx, extra)
		_, err := tx.ExecContext(ctx, `UPDATE accounts SET name=$2, platform=$3, type=$4, parent_account_id=$5 WHERE id=$1`, id, tc.name, tc.platform, tc.accountType, tc.parent)
		require.NoError(t, err)
		if tc.want {
			wantIDs = append(wantIDs, id)
		}
	}
	loads, err := repo.ListSchedulableAccountLoads(ctx)
	require.NoError(t, err)
	gotIDs := make([]int64, 0, len(loads))
	for _, load := range loads {
		gotIDs = append(gotIDs, load.ID)
	}
	require.ElementsMatch(t, wantIDs, gotIDs, "only non-shadow OpenAI OAuth accounts should be paused by TTFT metadata")
	accounts, err := repo.ListSchedulable(ctx)
	require.NoError(t, err)
	gotIDs = gotIDs[:0]
	for _, account := range accounts {
		gotIDs = append(gotIDs, account.ID)
	}
	require.ElementsMatch(t, wantIDs, gotIDs, "full Ent scheduling query must match the lightweight projection")
	_, err = tx.ExecContext(ctx, `INSERT INTO account_groups (account_id, group_id, priority, created_at)
		SELECT id, 123, 50, NOW() FROM accounts`)
	require.NoError(t, err)
	capacity, err := repo.ListSchedulableCapacityByGroupIDs(ctx, []int64{123})
	require.NoError(t, err)
	gotIDs = gotIDs[:0]
	for _, row := range capacity {
		gotIDs = append(gotIDs, row.AccountID)
	}
	require.ElementsMatch(t, wantIDs, gotIDs, "raw grouped capacity query must match Ent scheduling")
	groupRepo := newGroupRepositoryWithSQL(tx.Client(), tx)
	counts, err := groupRepo.loadAccountCounts(ctx, []int64{123})
	require.NoError(t, err)
	require.EqualValues(t, 6, counts[123].Total)
	require.EqualValues(t, len(wantIDs), counts[123].Active)
	require.Zero(t, counts[123].RateLimited)
}

